def generate_md(name, tpl):
    path = os.path.join(MD_DIR, f"{tpl['filename']}.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(tpl["md"])
    print(f"  [MD]   {path}")


def generate_docx(name, tpl):
    doc = Document()

    # 设置默认字体
    style = doc.styles["Normal"]
    font = style.font
    font.name = "等线"
    font.size = Pt(11)

    for part in tpl["docx_parts"]:
        ptype = part[0]

        if ptype == "para":
            text = part[1]
            fmt = part[2] if len(part) > 2 else {}
            p = doc.add_paragraph()
            run = p.add_run(text)
            if fmt.get("bold"):
                run.bold = True
            if fmt.get("italic"):
                run.italic = True
            if fmt.get("size"):
                run.font.size = Pt(fmt["size"])

        elif ptype == "table":
            rows_data = part[1]
            table = doc.add_table(rows=len(rows_data), cols=2, style="Table Grid")
            table.alignment = WD_TABLE_ALIGNMENT.CENTER
            for i, row_data in enumerate(rows_data):
                for j, cell_text in enumerate(row_data):
                    cell = table.cell(i, j)
                    cell.text = cell_text
                    for paragraph in cell.paragraphs:
                        for run in paragraph.runs:
                            run.font.size = Pt(10)

    path = os.path.join(DOCX_DIR, f"{tpl['filename']}.docx")
    doc.save(path)
    print(f"  [DOCX] {path}")


